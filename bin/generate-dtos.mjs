#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

/*
 * Generates separate files for enums and DTO classes from a
 * swagger-typescript-api generated data-contract file.
 *
 * Usage:
 *   nest-swagger-dto-generator <input-file> <output-dir> [--only Name1,Name2]
 *
 *   --only   comma-separated list of entity names (enums and interfaces)
 *            to export; when omitted all entities are exported
 */

const USAGE = `Usage:
  nest-swagger-dto-generator <input-file> <output-dir> [--only Name1,Name2] [--clean]

  <input-file>  path to swagger-typescript-api generated data-contracts file
  <output-dir>  folder where enum and DTO files will be written
  --only        optional comma-separated list of entity names to export
  --clean       wipe the output folder before generating (so that with
                --only the folder contains exactly the selected entities)
  --help        show this help
`;

function kebab(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

function dtoFileName(name) {
  if (/Dto$/.test(name)) {
    return kebab(name.slice(0, -3)) + '.dto.ts';
  }
  return kebab(name) + '.ts';
}

function relativeTsImport(fromDir, toFile) {
  let rel = path.relative(path.resolve(fromDir), path.resolve(toFile)).replace(/\\/g, '/');
  rel = rel.replace(/\.ts$/, '');
  return rel.startsWith('.') ? rel : './' + rel;
}

function quote(str) {
  return "'" + str.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

const GENERATED_HEADER = `/* eslint-disable */
/* tslint:disable */
// This file was generated by nest-swagger-dto-generator. Do not edit.
`;

function parseEntities(code) {
  const entities = [];
  let pos = 0;

  while (pos < code.length) {
    const exportIdx = code.indexOf('export', pos);
    if (exportIdx === -1) break;

    const match = /^export\s+(enum|interface|type)\s+(\w+)/.exec(code.slice(exportIdx));
    if (!match) {
      pos = exportIdx + 'export'.length;
      continue;
    }

    const kind = match[1];
    const name = match[2];
    pos = exportIdx + match[0].length;

    if (kind === 'type') {
      const semi = code.indexOf(';', pos);
      pos = semi === -1 ? code.length : semi + 1;
      continue;
    }

    const open = code.indexOf('{', pos);
    if (open === -1) break;

    let depth = 1;
    let j = open + 1;
    while (j < code.length && depth > 0) {
      const ch = code[j];
      if (ch === '/' && code[j + 1] === '*') {
        const end = code.indexOf('*/', j + 2);
        j = end === -1 ? code.length : end + 2;
        continue;
      }
      if (ch === '/' && code[j + 1] === '/') {
        const end = code.indexOf('\n', j);
        j = end === -1 ? code.length : end + 1;
        continue;
      }
      if (ch === '"' || ch === "'") {
        const q = ch;
        let k = j + 1;
        while (k < code.length) {
          if (code[k] === '\\') {
            k += 2;
            continue;
          }
          k++;
          if (code[k - 1] === q) break;
        }
        j = k;
        continue;
      }
      if (ch === '{') depth++;
      else if (ch === '}') depth--;
      j++;
    }

    entities.push({kind, name, body: code.slice(open + 1, j - 1)});
    pos = j;
  }

  return entities;
}

function parseInterface(entity) {
  const fields = [];
  const lines = entity.body.split('\n');
  let comment = [];

  for (const raw of lines) {
    const line = raw.trim();
    if (!line) continue;

    if (/^\*\//.test(line)) continue;
    const singleLineComment = /^\/\*\*\s*(.*?)\s*\*\/\s*$/.exec(line);
    if (singleLineComment) {
      comment = [singleLineComment[1]];
      continue;
    }
    if (/^\/\*\*/.test(line)) {
      comment = [];
      continue;
    }
    if (line.startsWith('*')) {
      const content = line.replace(/^\*\s?/, '').trim();
      if (content) comment.push(content);
      continue;
    }

    const m = /^(\"?[A-Za-z_$][\w$-]*\"?)(\??)\s*:\s*(.+?)\s*;\s*$/.exec(line);
    if (m) {
      fields.push({name: m[1], optional: m[2] === '?', type: m[3].trim(), comment});
      comment = [];
    }
  }

  return fields;
}

function parseComment(lines) {
  const description = [];
  let deprecated = false;
  let example;

  for (const line of lines) {
    if (line.startsWith('@deprecated')) {
      deprecated = true;
      continue;
    }
    if (line.startsWith('@example')) {
      example = line.replace(/^@example\s*/, '').trim();
      continue;
    }
    description.push(line);
  }

  return {description: description.join(' ').trim(), deprecated, example};
}

function renderExample(raw) {
  const value = raw.trim();
  if (/^[+-]?\d+(\.\d+)?$/.test(value)) return value;
  if (value === 'true' || value === 'false' || value === 'null' || value === 'undefined') return value;
  if (/^[\[{]/.test(value) && /[\]}]$/.test(value)) return value;
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    return value;
  }
  return quote(value);
}

function renderApiProperty(parsed, extraOpts = []) {
  const opts = [];
  if (parsed.description) opts.push(`description: ${quote(parsed.description)}`);
  if (parsed.example) opts.push(`example: ${renderExample(parsed.example)}`);
  if (parsed.deprecated) opts.push(`deprecated: true`);
  opts.push(...extraOpts);
  if (!opts.length) return '@ApiProperty()';
  return `@ApiProperty({${opts.join(', ')}})`;
}

function referencedEntities(type, entityMap) {
  const hits = [];
  for (const token of type.split(/[^\w$]+/)) {
    if (!token || !/^[A-Z_$]/.test(token)) continue;
    const kind = entityMap[token];
    if (kind && !hits.some((h) => h.name === token)) {
      hits.push({name: token, kind});
    }
  }
  return hits;
}

function apiTypeOptions(type, entityMap) {
  const refs = referencedEntities(type, entityMap);
  if (refs.length !== 1) return [];
  const ref = refs[0];
  const opts = [];
  if (ref.kind === 'enum') {
    opts.push(`enum: ${ref.name}`, `enumName: '${ref.name}'`);
  } else {
    opts.push(`type: () => ${ref.name}`);
  }
  if (/\[\]\s*$/.test(type)) opts.push('isArray: true');
  return opts;
}

function renderEnum(entity) {
  const lines = entity.body.split('\n').map((l) => l.trim());
  while (lines.length && lines[0] === '') lines.shift();
  while (lines.length && lines[lines.length - 1] === '') lines.pop();

  const body = lines.map((l) => (l === '' ? '' : '  ' + l)).join('\n');
  return `export enum ${entity.name} {\n${body}\n}\n`;
}

function renderDto(entity, fields, entityMap, interfaceImport) {
  const fieldLines = [];
  for (const f of fields) {
    const parsed = parseComment(f.comment);
    const extraOpts = [];
    if (f.optional) extraOpts.push('required: false');
    extraOpts.push(...apiTypeOptions(f.type, entityMap));
    fieldLines.push('  ' + renderApiProperty(parsed, extraOpts));
    fieldLines.push(`  ${f.name}${f.optional ? '?' : ''}: ${f.type};`);
    fieldLines.push('');
  }
  while (fieldLines.length && fieldLines[fieldLines.length - 1] === '') fieldLines.pop();

  const refs = [...new Map(
    fields.flatMap((f) => referencedEntities(f.type, entityMap))
      .filter((r) => r.name !== entity.name)
      .map((r) => [r.name, r]),
  ).values()].sort((a, b) => a.name.localeCompare(b.name));

  const header = [];
  if (fields.length) header.push("import {ApiProperty} from '@nestjs/swagger';");

  const relativeImports = [];
  if (interfaceImport) {
    relativeImports.push(`import {${entity.name} as ${entity.name}Interface} from '${interfaceImport}';`);
  }
  relativeImports.push(...refs.map((r) => {
    if (r.kind === 'enum') {
      return `import {${r.name}} from './${kebab(r.name)}.enum';`;
    }
    return `import {${r.name}} from './${dtoFileName(r.name).replace(/\.ts$/, '')}';`;
  }));
  if (relativeImports.length) {
    header.push('');
    header.push(...relativeImports);
  }

  const parts = [];
  if (header.length) parts.push(header.join('\n'), '');
  parts.push(`export class ${entity.name} implements ${entity.name}Interface {`);
  parts.push(fieldLines.join('\n'));
  parts.push('}');
  return parts.join('\n') + '\n';
}

function parseArgs(argv) {
  const positional = [];
  let input;
  let output;
  let only = null;
  let clean = false;

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') {
      process.stdout.write(USAGE);
      process.exit(0);
    }
    if (arg === '--only') {
      only = argv[++i];
    } else if (arg.startsWith('--only=')) {
      only = arg.slice('--only='.length);
    } else if (arg === '--clean') {
      clean = true;
    } else {
      positional.push(arg);
    }
  }

  if (positional.length > 0) input = positional[0];
  if (positional.length > 1) output = positional[1];

  if (!input || !output) {
    process.stderr.write(USAGE);
    process.exit(1);
  }

  return {input, output, only, clean};
}

function main() {
  const {input, output, only, clean} = parseArgs(process.argv.slice(2));

  const code = fs.readFileSync(input, 'utf8');
  const entities = parseEntities(code);

  let selected = entities;
  if (only) {
    const wanted = only.split(',').map((s) => s.trim()).filter(Boolean);
    selected = entities.filter((e) => wanted.includes(e.name));
    const found = new Set(selected.map((e) => e.name));
    for (const w of wanted) {
      if (!found.has(w)) {
        process.stderr.write(`WARN: entity not found: ${w}\n`);
      }
    }
  }

  if (!selected.length) {
    process.stderr.write('No entities to export.\n');
    process.exit(1);
  }

  if (clean) {
    fs.rmSync(output, {recursive: true, force: true});
    process.stdout.write(`Cleaned output folder: ${output}\n`);
  }
  fs.mkdirSync(output, {recursive: true});

  const entityMap = {};
  for (const e of entities) {
    if (e.kind === 'enum' || e.kind === 'interface') entityMap[e.name] = e.kind;
  }
  let exportsCount = 0;

  for (const e of selected) {
    if (e.kind === 'enum') {
      const file = path.join(output, kebab(e.name) + '.enum.ts');
      fs.writeFileSync(file, GENERATED_HEADER + renderEnum(e));
      exportsCount++;
      process.stdout.write(`ENUM      ${e.name} -> ${file}\n`);
    } else if (e.kind === 'interface') {
      const file = path.join(output, dtoFileName(e.name));
      fs.writeFileSync(
        file,
        GENERATED_HEADER + renderDto(e, parseInterface(e), entityMap, relativeTsImport(output, input)),
      );
      exportsCount++;
      process.stdout.write(`DTO       ${e.name} -> ${file}\n`);
    } else if (e.kind === 'type') {
      process.stdout.write(`SKIPPED   ${e.name} (type alias)\n`);
    }
  }

  process.stdout.write(`\nExported ${exportsCount} entities to ${output}\n`);
}

main();